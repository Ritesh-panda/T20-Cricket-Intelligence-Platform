"""
Canonical Pydantic v2 schemas for Phase 5 Semantic Embeddings, Topic Discovery, and Narrative Intelligence.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class CorpusType(str, Enum):
    EDITORIAL = "editorial"
    COMMENTARY = "commentary"
    COMBINED = "combined"


class MatchStatus(str, Enum):
    ACCEPTED = "ACCEPTED"
    NEEDS_REVIEW = "NEEDS_REVIEW"
    UNRESOLVED = "UNRESOLVED"


class EmbeddingMetadataRecord(BaseModel):
    """Metadata record for a stored dense vector embedding."""
    embedding_id: str = Field(description="Deterministic ID: emb_{sha256(norm_id + model_version)[:16]}")
    norm_id: str = Field(description="Foreign key to normalized_texts.norm_id")
    source_type: str = Field(description="article_paragraph or commentary")
    source_id: str = Field(description="Reference ID of parent text")
    model_version: str = Field(description="Identifier of embedding model used")
    dimension: int = Field(default=384, description="Vector dimension")
    text_hash: str = Field(description="SHA-256 hash of clean text at time of embedding")
    is_test_double: bool = Field(default=False, description="True if generated by test double")
    vector_file_path: Optional[str] = Field(default=None, description="Path to parquet or npy vector storage")
    vector_index: Optional[int] = Field(default=None, description="Index in vector storage file")
    created_at: datetime = Field(default_factory=_utcnow)


class TopicRunRecord(BaseModel):
    """Metadata record for a topic clustering execution run."""
    run_id: str = Field(description="Unique run ID: topic_run_{timestamp}_{hex}")
    corpus_type: CorpusType = Field(description="editorial, commentary, or combined")
    algorithm: str = Field(description="kmeans, dbscan, etc.")
    n_clusters_requested: Optional[int] = Field(default=None)
    n_clusters_found: int = Field(default=0)
    n_noise_points: int = Field(default=0)
    parameters_json: str = Field(default="{}", description="JSON string of hyperparameters")
    silhouette_score: Optional[float] = Field(default=None)
    davies_bouldin_index: Optional[float] = Field(default=None)
    created_at: datetime = Field(default_factory=_utcnow)


class TopicClusterRecord(BaseModel):
    """Represents a discovered topic cluster."""
    cluster_id: str = Field(description="Format: {run_id}_c{index}")
    run_id: str = Field(description="Foreign key to topic_runs.run_id")
    cluster_index: int = Field(description="Cluster numeric index (-1 for noise)")
    topic_label: str = Field(description="Human-readable descriptive label derived from c-TF-IDF")
    keywords: List[str] = Field(default_factory=list, description="Top salient keywords")
    doc_count: int = Field(default=0, description="Number of assigned documents")
    representative_doc_ids: List[str] = Field(default_factory=list, description="IDs of documents closest to centroid")
    intra_cluster_similarity: Optional[float] = Field(default=None)
    is_noise: bool = Field(default=False, description="True if unassigned outlier cluster")


class TopicAssignmentRecord(BaseModel):
    """Individual document assignment to a topic cluster."""
    assignment_id: str = Field(description="Format: assign_{cluster_id}_{norm_id[:8]}")
    cluster_id: str = Field(description="Foreign key to topic_clusters.cluster_id")
    norm_id: str = Field(description="Foreign key to normalized_texts.norm_id")
    source_id: str = Field(description="Original parent document ID")
    distance_to_centroid: Optional[float] = Field(default=None)
    membership_score: float = Field(default=1.0, description="Soft membership or similarity score")


class TopicEvaluationMetrics(BaseModel):
    """Comprehensive evaluation metrics for a clustering run."""
    n_documents: int
    n_clusters: int
    n_noise: int
    noise_ratio: float
    silhouette_score: Optional[float] = None
    davies_bouldin_index: Optional[float] = None
    cluster_sizes: Dict[int, int] = Field(default_factory=dict)
    min_cluster_size: int = 0
    max_cluster_size: int = 0
    mean_cluster_size: float = 0.0
    mean_intra_cluster_similarity: Optional[float] = None
    mean_inter_cluster_similarity: Optional[float] = None
    notes: List[str] = Field(default_factory=list)


class CrossSourceMatchRecord(BaseModel):
    """Semantic link between an editorial paragraph and a commentary delivery."""
    match_link_id: str = Field(description="Deterministic ID: xmatch_{sha256(ed_id + comm_id)[:16]}")
    editorial_norm_id: str = Field(description="Foreign key to editorial normalized_texts")
    editorial_source_id: str
    commentary_norm_id: str = Field(description="Foreign key to commentary normalized_texts")
    commentary_source_id: str
    match_id: Optional[str] = Field(default=None, description="Ground-truth match ID if linked")
    similarity_score: float = Field(description="Cosine similarity between vector representations")
    status: MatchStatus = Field(default=MatchStatus.UNRESOLVED)
    confidence: float = Field(default=0.0)
    matching_method: str = Field(default="hybrid_vector_and_entity")
    evidence: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=_utcnow)


class NarrativeTimelinePoint(BaseModel):
    """Discrete time point observation in a narrative evolution timeline."""
    bucket_label: str = Field(description="Date or timestamp bucket (e.g. 2024-06-29, or match phase)")
    doc_count: int = 0
    mean_sentiment: float = 0.0
    sentiment_distribution: Dict[str, int] = Field(default_factory=dict)
    top_topics: List[Dict[str, Any]] = Field(default_factory=list)
    top_entities: List[Dict[str, Any]] = Field(default_factory=list)
    match_events_count: int = 0
    observed_timestamps_count: int = 0
    inferred_timestamps_count: int = 0
